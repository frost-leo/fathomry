CREATE TRIGGER protect_english_locale
BEFORE DELETE ON {{target}}.i18n_locale
FOR EACH ROW WHEN (LOWER(OLD.code) = 'en')
EXECUTE FUNCTION {{target}}.reject_catalog_change();
