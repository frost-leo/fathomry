// Package minio exposes the bounded MinIO object-storage Adapter through public
// contracts, without granting Internal, SDK-client or source-shutdown authority.
//
// Validate and Recommend prepare Settings and public objectstore budgets without
// service I/O. Open owns a source and performs bucket-HEAD readiness. Its Client
// supports direct use; Handle and Using compose public resource Fixed/Follow
// bindings. Operations return read-only public receipts alongside independently
// owned evidence. Borrowed Readers/Writers remain in use until actual release.
//
// BeginMultipart and Enumerate retain one generation and bounded serial work.
// Finalization consumes existing responsibility even when admission/evidence is
// full. Presign grants only explicitly permitted GET/HEAD/PUT bearer capabilities;
// issuance is not an object acknowledgement, and Close does not revoke a URL.
//
// Local cleanup, remote effects, integrity checks and evidence reception remain
// distinct. No bucket administration, automatic replay, durable upload/cursor
// format, universal SDK interface or Temporal Workflow I/O is supplied.
